"""Verify reviewed vendor bytes and pinned upstream source without importing MLX.

The manifest is a review artifact, never regenerated by CI. The wheel is read as
ZIP data after SHA-256 verification; it is never installed, extracted, or imported.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "scripts/vendored-provenance.json"
VENDOR = "rapid_mlx/models/mlx_vlm_vendored"
MAX_WHEEL_BYTES = 30 * 1024 * 1024


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def verify(root: Path, manifest: dict, wheel: bytes) -> None:
    if digest(wheel) != manifest["wheel"]["sha256"]:
        raise ValueError("Pinned upstream wheel SHA-256 mismatch")
    vendor = root / VENDOR
    actual = {
        path.relative_to(vendor).as_posix()
        for path in vendor.rglob("*")
        if path.is_file() and "__pycache__" not in path.parts
    }
    expected = set(manifest["files"])
    if actual != expected:
        raise ValueError(
            f"Vendor inventory drift: added={sorted(actual - expected)}, "
            f"missing={sorted(expected - actual)}"
        )
    with zipfile.ZipFile(io.BytesIO(wheel)) as archive:
        for name, entry in manifest["files"].items():
            path = vendor / name
            if (
                path.is_symlink()
                or digest(path.read_bytes()) != entry["vendored_sha256"]
            ):
                raise ValueError(f"Unreviewed vendor content: {name}")
            if "wheel_path" in entry:
                upstream = archive.read(entry["wheel_path"])
                if digest(upstream) != entry["upstream_sha256"]:
                    raise ValueError(f"Upstream provenance mismatch: {name}")
            elif (
                "upstream_commit" not in entry
                and entry.get("origin") != "reviewed-glue"
            ):
                raise ValueError(f"Missing upstream provenance: {name}")
    # Independently honor the newer MiniCPM snapshot inventory already shipped
    # with the source. It is itself included in the complete-tree digest gate.
    newer = vendor / "models/minicpmv4_7"
    inventory = json.loads((newer / "provenance.json").read_text())
    if set(inventory["files"]) != {path.name for path in newer.glob("*.py")}:
        raise ValueError("MiniCPM upstream inventory drift")
    for name, entry in inventory["files"].items():
        source = (newer / name).read_bytes()
        if digest(source) != entry["vendored_sha256"]:
            raise ValueError(f"MiniCPM reviewed digest mismatch: {name}")
        if inventory["upstream_commit"].encode() not in source:
            raise ValueError(f"MiniCPM source commit missing: {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--wheel", type=Path, help="Use an already downloaded pinned wheel"
    )
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    if args.wheel:
        wheel = args.wheel.read_bytes()
    else:
        # Immutable PyPI artifact URL + independent reviewed digest. No package
        # resolver, dependency installation, or package code execution occurs.
        with urllib.request.urlopen(manifest["wheel"]["url"], timeout=60) as response:
            wheel = response.read(MAX_WHEEL_BYTES + 1)
        if len(wheel) > MAX_WHEEL_BYTES:
            raise ValueError("Upstream wheel exceeds bounded source artifact size")
    verify(ROOT, manifest, wheel)
    print(
        f"Verified {len(manifest['files'])} reviewed vendor files against pinned provenance"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
