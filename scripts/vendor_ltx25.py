"""Vendor the pinned LTX-2.5 MLX runtime into this source tree.

The runtime is distributed inside rapid-mlx as two top-level packages,
``ltx_core_mlx`` and ``ltx_pipelines_mlx``, copied from the pinned
upstream source archive.  ``--update`` reproduces that copy from the archive;
``--check`` verifies the resulting tree including our local-snapshot patch.  The Desktop sidecar
build runs ``--check`` so a signed app can never embed an unaudited runtime.

This script is deliberately self-contained: importing ``rapid_mlx.video`` would
pull in the MLX-backed video engine, which is not needed to copy files.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

LTX25_RUNTIME_COMMIT = "57952288076766abe27dda3a774b2c24f7346977"
LTX25_RUNTIME_REPOSITORY = "https://github.com/MrMoferFRAN/ltx-2-mlx.git"
LTX25_RUNTIME_VERSION = "0.14.15"
LTX25_RUNTIME_SHA256 = (
    "fa9a66a0c78721c3dce51d0f1dadcabad060682410303be748e529a846a9d5c9"
)
LTX25_RUNTIME_ARCHIVE_URL = (
    f"https://github.com/MrMoferFRAN/ltx-2-mlx/archive/{LTX25_RUNTIME_COMMIT}.tar.gz"
)
LTX25_ARCHIVE_ROOT = f"ltx-2-mlx-{LTX25_RUNTIME_COMMIT}"

# package directory -> upstream source directory inside the archive.
LTX25_PACKAGES = {
    "ltx_core_mlx": f"{LTX25_ARCHIVE_ROOT}/packages/ltx-core-mlx/src/ltx_core_mlx",
    "ltx_pipelines_mlx": (
        f"{LTX25_ARCHIVE_ROOT}/packages/ltx-pipelines-mlx/src/ltx_pipelines_mlx"
    ),
}

PROVENANCE_FILENAME = "_vendored.py"
_GENERATED_FILES = frozenset({PROVENANCE_FILENAME, "LICENSE", "NOTICE"})
_SKIPPED_DIRECTORIES = frozenset({"__pycache__"})

_PROVENANCE_TEMPLATE = '''\
"""Provenance for the vendored LTX-2.5 runtime package.

Generated by ``scripts/vendor_ltx25.py``; do not edit by hand.
"""

REPOSITORY = {repository!r}
COMMIT = {commit!r}
VERSION = {version!r}
PACKAGE = {package!r}
TREE_SHA256 = {tree_sha256!r}
'''

_NOTICE_TEMPLATE = """\
LTX-2.5 MLX runtime — {package}

Vendored from {repository} at commit {commit} (package version {version}).
Source archive: {archive}
Archive SHA-256: {archive_sha256}

Copyright (c) 2025 dgrauet. Licensed under the MIT License; the LICENSE file
in this directory is a verbatim copy of the upstream license text.

The pipeline download helpers carry the reproducible local-snapshot patch in
scripts/patches/ltx25-local-snapshots.patch. This distribution also adds
this NOTICE, the LICENSE copy, and the generated ``{provenance}``
provenance metadata (repository, commit, version, package name, tree digest).
The tree digest covers every upstream file and excludes those three files.

Model weights are not distributed here — they are downloaded at runtime from
their publishers under their own separate licenses.
"""


class VendorError(RuntimeError):
    """Actionable failure from the vendoring/check step."""


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _iter_upstream_files(package_dir: Path) -> list[Path]:
    """Return every upstream file, excluding generated metadata and caches."""
    files: list[Path] = []
    for path in sorted(package_dir.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(package_dir)
        if relative.parts[0] in _SKIPPED_DIRECTORIES:
            continue
        if path.suffix == ".pyc":
            continue
        if len(relative.parts) == 1 and relative.name in _GENERATED_FILES:
            continue
        files.append(relative)
    return files


def tree_digest(package_dir: Path) -> str:
    """Deterministic digest of the upstream files in one vendored package."""
    digest = hashlib.sha256()
    for relative in _iter_upstream_files(package_dir):
        digest.update(relative.as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update((package_dir / relative).read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def read_provenance(package_dir: Path) -> dict[str, str] | None:
    """Read the generated provenance metadata without importing the package."""
    try:
        text = (package_dir / PROVENANCE_FILENAME).read_text(encoding="utf-8")
    except OSError:
        return None
    values: dict[str, str] = {}
    for name in ("REPOSITORY", "COMMIT", "VERSION", "PACKAGE", "TREE_SHA256"):
        match = re.search(rf'^{name}\s*=\s*["\']([^"\']+)["\']\s*$', text, re.MULTILINE)
        if match is None:
            return None
        values[name] = match.group(1)
    return values


def _validate_archive_member(member: tarfile.TarInfo) -> None:
    name = member.name
    path = Path(name)
    if path.is_absolute() or ".." in path.parts:
        raise VendorError(f"archive contains an unsafe path: {name}")
    if member.issym() or member.islnk() or member.isdev():
        raise VendorError(f"archive contains a non-regular entry: {name}")
    if not (member.isfile() or member.isdir()):
        raise VendorError(f"archive contains an unsupported entry: {name}")


def extract_archive(archive: Path, destination: Path) -> None:
    """Extract a verified tarball, rejecting paths outside *destination*."""
    root = destination.resolve()
    try:
        with tarfile.open(archive, mode="r:gz") as source:
            members = source.getmembers()
            for member in members:
                _validate_archive_member(member)
                target = (destination / member.name).resolve()
                if not target.is_relative_to(root):
                    raise VendorError(
                        f"archive entry escapes the destination: {member.name}"
                    )
            if hasattr(tarfile, "data_filter"):
                source.extractall(destination, members=members, filter="data")
            else:
                source.extractall(destination, members=members)
    except (OSError, tarfile.TarError) as exc:
        raise VendorError(f"could not extract the source archive: {exc}") from exc


def download_archive(destination: Path) -> None:
    """Download the pinned archive with a bounded read and verified digest."""
    try:
        with (
            urllib.request.urlopen(  # noqa: S310 - pinned HTTPS URL
                LTX25_RUNTIME_ARCHIVE_URL, timeout=120
            ) as response,
            destination.open("wb") as target,
        ):
            shutil.copyfileobj(response, target)
    except OSError as exc:
        raise VendorError(f"could not download the source archive: {exc}") from exc
    actual = _sha256_file(destination)
    if actual != LTX25_RUNTIME_SHA256:
        raise VendorError(
            "the LTX-2.5 source archive failed integrity verification: "
            f"expected {LTX25_RUNTIME_SHA256}, got {actual}"
        )


def _copy_package(source: Path, destination: Path) -> None:
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(
        source,
        destination,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )


def _write_provenance(package: str, destination: Path, tree_sha256: str) -> None:
    (destination / PROVENANCE_FILENAME).write_text(
        _PROVENANCE_TEMPLATE.format(
            repository=LTX25_RUNTIME_REPOSITORY,
            commit=LTX25_RUNTIME_COMMIT,
            version=LTX25_RUNTIME_VERSION,
            package=package,
            tree_sha256=tree_sha256,
        ),
        encoding="utf-8",
    )


def _write_notice(package: str, destination: Path) -> None:
    (destination / "NOTICE").write_text(
        _NOTICE_TEMPLATE.format(
            package=package,
            repository=LTX25_RUNTIME_REPOSITORY,
            commit=LTX25_RUNTIME_COMMIT,
            version=LTX25_RUNTIME_VERSION,
            archive=LTX25_RUNTIME_ARCHIVE_URL,
            archive_sha256=LTX25_RUNTIME_SHA256,
            provenance=PROVENANCE_FILENAME,
        ),
        encoding="utf-8",
    )


def apply_local_snapshot_patch(root: Path) -> None:
    """Reapply the reviewed downstream download boundary after vendoring."""
    patch = Path(__file__).with_name("patches") / "ltx25-local-snapshots.patch"
    subprocess.run(["git", "apply", str(patch)], cwd=root, check=True)


def update(root: Path, tarball: Path | None) -> None:
    """Replace the vendored packages with the pinned upstream snapshot."""
    with tempfile.TemporaryDirectory(prefix="rapidmlx-ltx25-vendor-") as temporary:
        workspace = Path(temporary)
        archive = tarball.expanduser().resolve() if tarball is not None else None
        if archive is None:
            archive = workspace / "ltx-2-mlx.tar.gz"
            download_archive(archive)
        elif not archive.is_file():
            raise VendorError(f"tarball does not exist: {archive}")
        else:
            actual = _sha256_file(archive)
            if actual != LTX25_RUNTIME_SHA256:
                raise VendorError(
                    "the LTX-2.5 source archive failed integrity verification: "
                    f"expected {LTX25_RUNTIME_SHA256}, got {actual}"
                )
        extract_archive(archive, workspace)
        license_source = workspace / LTX25_ARCHIVE_ROOT / "LICENSE"
        if not license_source.is_file():
            raise VendorError("the source archive does not contain its LICENSE")
        for package, source_name in LTX25_PACKAGES.items():
            source = workspace / source_name
            if not source.is_dir():
                raise VendorError(f"the source archive lacks {source_name}")
            destination = root / package
            _copy_package(source, destination)
            shutil.copyfile(license_source, destination / "LICENSE")
            if package == "ltx_pipelines_mlx":
                apply_local_snapshot_patch(root)
            _write_notice(package, destination)
            _write_provenance(package, destination, tree_digest(destination))
            print(f"vendored {package} -> {destination}")


def check(root: Path) -> list[str]:
    """Return every reason the vendored tree no longer matches the pin."""
    problems: list[str] = []
    for package in LTX25_PACKAGES:
        destination = root / package
        if not destination.is_dir():
            problems.append(f"{package}: package directory is missing")
            continue
        provenance = read_provenance(destination)
        if provenance is None:
            problems.append(f"{package}: {PROVENANCE_FILENAME} is missing or invalid")
            continue
        expected = {
            "REPOSITORY": LTX25_RUNTIME_REPOSITORY,
            "COMMIT": LTX25_RUNTIME_COMMIT,
            "VERSION": LTX25_RUNTIME_VERSION,
            "PACKAGE": package,
        }
        for name, value in expected.items():
            if provenance[name] != value:
                problems.append(
                    f"{package}: {name} is {provenance[name]!r}, expected {value!r}"
                )
        if not (destination / "LICENSE").is_file():
            problems.append(f"{package}: LICENSE is missing")
        if not (destination / "NOTICE").is_file():
            problems.append(f"{package}: NOTICE is missing")
        actual = tree_digest(destination)
        if actual != provenance["TREE_SHA256"]:
            problems.append(
                f"{package}: vendored tree digest changed "
                f"({actual} != {provenance['TREE_SHA256']}); "
                "run scripts/vendor_ltx25.py --update and review the diff"
            )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--update",
        action="store_true",
        help="download the pinned archive and replace the vendored packages",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="verify the vendored packages still match the pinned archive",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="source tree root that contains the vendored packages",
    )
    parser.add_argument(
        "--tarball",
        type=Path,
        default=None,
        help="reuse an already-downloaded pinned archive instead of fetching",
    )
    args = parser.parse_args(argv)
    root = args.root.expanduser().resolve()
    try:
        if args.update:
            update(root, args.tarball)
            return 0
        problems = check(root)
    except VendorError as exc:
        print(f"vendor_ltx25: {exc}", file=sys.stderr)
        return 1
    if problems:
        print("vendor_ltx25: vendored LTX-2.5 runtime is out of sync:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    print(
        f"vendor_ltx25: vendored LTX-2.5 runtime matches commit {LTX25_RUNTIME_COMMIT}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
