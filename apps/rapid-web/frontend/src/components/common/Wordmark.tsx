/**
 * The Rapid-MLX lockup: the `R` mark plus the wordmark. `-MLX` is a
 * superscript mono tag.
 *
 * `mark` is opt-out because the two places this renders want different
 * things: the sign-in gate stacks a large mark above the name, while the
 * sidebar sets them side by side.
 */
export function Wordmark({ className, mark = true }: { className?: string; mark?: boolean }) {
  return (
    // `inline-flex`, not `flex`: this is set as text and sizes itself from the
    // font, so the mark can be sized in `em` and track the wordmark whatever
    // the caller sets `text-*` to.
    <span className={cn('inline-flex items-center gap-[0.34em] font-semibold tracking-tight', className)}>
      {mark ? <RapidMark className="size-[2em] shrink-0" /> : null}
      <span className="truncate text-sm">
        Rapid-MLX
      </span>
    </span>
  );
}
