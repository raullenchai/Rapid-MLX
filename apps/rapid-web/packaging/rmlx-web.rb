  # pydantic-core is a Rust extension and every resource below is an sdist, so
  # a source build compiles it (~5 min). Build-time only: pouring a bottle
  # never invokes rust, and a source build installs it without user action.
  depends_on "rust" => :build

  depends_on "python@3.12"

  # The engine, supplied as a command on PATH rather than as an import.
  # rmlx_web deliberately does not depend on rapid-mlx as a distribution —
  # supervisor.py drives `rapid-mlx serve` as a subprocess and locates it
  # with shutil.which. A brew-installed engine therefore satisfies it from
  # outside this virtualenv, which is why the isolation below is harmless.
  depends_on "rapid-mlx"

  # Every dependency is vendored as a resource rather than a formula.
  # Two of the names collide with unrelated software in homebrew-core:
