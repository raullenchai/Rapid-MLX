  def caveats
    <<~EOS
      Start the server with:
        rmlx-web

      It prints a URL and, when bound to anything other than loopback, an
      access token. No model is loaded at startup — pick one in the page.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/rmlx-web --version")

    # Starlette imports multipart support only when an upload is parsed, so
    # serving the HTML shell below would not catch a missing resource.
    system libexec/"bin/python", "-c", "import python_multipart"

    # The engine must be reachable as a command: rmlx_web resolves it with
    # shutil.which at startup, so a broken dependency surfaces here rather
    # than as a runtime error on the user's first page load.
    assert_path_exists formula_opt_bin("rapid-mlx")/"rapid-mlx"

    # Serve the page and fetch the shell. Startup resolves the engine
    # before binding, so a successful GET also proves the dependency above
    # is reachable the way supervisor.py looks for it.
    port = free_port
    pid = spawn bin/"rmlx-web", "--port", port.to_s
    begin
      sleep 15
      assert_match "<!doctype html", shell_output("curl -fsS http://127.0.0.1:#{port}/").downcase
    ensure
      Process.kill "TERM", pid
      Process.wait pid
    end
  end
