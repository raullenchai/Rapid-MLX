def _isolated_python_environment() -> dict[str, str]:
    """Return an environment that does not pin a child to Rapid's Python.

    The signed desktop sidecar deliberately exports ``PYTHONHOME`` and
    ``PYTHONPATH`` so its own interpreter cannot import host packages.  Those
    variables must not cross the runtime boundary: uv's build-isolation
    interpreters and the provisioned LTX interpreter otherwise try to start
    with Rapid's stdlib/site-packages and fail before importing ``encodings``.
    """
    environment = os.environ.copy()
    environment.pop("PYTHONHOME", None)
    environment.pop("PYTHONPATH", None)
    return environment


def is_ltx25_model(model_name: str | None) -> bool:
    """Return whether a model identifier explicitly selects LTX-2.5."""
    if not model_name:
        return False
    normalized = model_name.casefold().replace("_", "-")
    return normalized.rsplit("/", 1)[-1] == "ltx-2.5-mlx-q8"


def resolve_ltx25_runtime() -> str | None:
    """Resolve the explicit override only when it is at the audited revision.

    There is deliberately no PATH discovery: the runtime now ships inside the
    rapid-mlx distribution, so a stray ``ltx-2-mlx`` on PATH is never an
    implicit fallback for a damaged bundled copy.
    """
    override = os.environ.get("RAPID_MLX_LTX25_RUNTIME", "").strip()
    if not override:
        return None
    candidate = Path(override).expanduser()
    if candidate.is_file() and os.access(candidate, os.X_OK):
        absolute = str(candidate.absolute())
        return absolute if _runtime_revision(absolute) == LTX25_RUNTIME_COMMIT else None
    return None


def _install_root() -> Path:
    """Return the directory that contains the ``rapid_mlx`` package."""
    import rapid_mlx

    return Path(rapid_mlx.__file__).resolve().parent.parent


def _read_vendored_provenance(package_dir: Path) -> dict[str, str] | None:
    """Read the generated provenance metadata without importing the package."""
    try:
        text = (package_dir / LTX25_PROVENANCE_FILE).read_text(encoding="utf-8")
    except OSError:
        return None
    values: dict[str, str] = {}
    for name in ("REPOSITORY", "COMMIT", "VERSION", "PACKAGE", "TREE_SHA256"):
        match = re.search(rf'^{name}\s*=\s*["\']([^"\']+)["\']\s*$', text, re.MULTILINE)
        if match is None:
            return None
        values[name] = match.group(1)
    return values


def _vendored_files(package_dir: Path) -> list[Path]:
    """List the audited files exactly as ``scripts/vendor_ltx25.py`` does."""
    files: list[Path] = []
    for path in sorted(package_dir.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(package_dir)
        if relative.parts[0] == "__pycache__":
            continue
        if path.suffix == ".pyc":
            continue
        if len(relative.parts) == 1 and relative.name in LTX25_GENERATED_FILES:
            continue
        files.append(relative)
    return files


def _tree_digest(package_dir: Path) -> str:
    """Digest the vendored tree the way the vendoring script recorded it."""
    files = _vendored_files(package_dir)
    stats = {relative.as_posix(): (package_dir / relative).stat() for relative in files}
    signature = tuple(
        sorted((name, stat.st_mtime_ns, stat.st_size) for name, stat in stats.items())
    )
    key = (str(package_dir), signature)
    cached = _TREE_DIGEST_CACHE.get(key)
    if cached is not None:
        return cached
    digest = hashlib.sha256()
    for relative in files:
        digest.update(relative.as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update((package_dir / relative).read_bytes())
        digest.update(b"\0")
    value = digest.hexdigest()
    _TREE_DIGEST_CACHE[key] = value
    return value


def _resolve_vendored_package(
    package: str, install_root: Path
) -> tuple[Path | None, tuple[LTX25RuntimeReason, str] | None]:
    """Return the package directory, or why it cannot be trusted.

    The directory must be the top-level package inside the same install root
    that hosts ``rapid_mlx`` (wheel ``site-packages``, an editable source tree
    or the Desktop sidecar's ``site-packages``). ``spec.origin`` and every
    search location are checked, so a foreign module origin or a package split
    across locations cannot pass on labels alone.
    """
    try:
        spec = importlib.util.find_spec(package)
    except (ImportError, ModuleNotFoundError, ValueError):
        spec = None
    if spec is None:
        return None, None
    locations = {
        Path(location).resolve() for location in spec.submodule_search_locations or ()
    }
    if len(locations) != 1:
        return None, (
            "shadowed",
            f"{package} resolves from {len(locations)} import locations; "
            "only one audited copy can be trusted.",
        )
    directory = locations.pop()
    origin = spec.origin
    if origin is None or not Path(origin).resolve().is_relative_to(directory):
        return None, (
            "shadowed",
            f"{package} module origin {origin!r} does not match its package "
            f"directory {directory}.",
        )
    if directory.parent != install_root or directory.name != package:
        return None, (
            "shadowed",
            f"{package} resolves outside this rapid-mlx installation "
            f"({directory}); a shadowing copy is not trusted.",
        )
    return directory, None


def _vendored_runtime() -> LTX25Runtime:
    """Classify the runtime vendored inside this rapid-mlx installation.

    Trusted only when both packages resolve from this distribution's install
    root, carry the pinned provenance labels, and their on-disk files still
    match the recorded tree digest. A partially installed, modified or shadowed
    copy is ``corrupt`` with a structured reason; never silently fall through
    to another runtime.
    """
    install_root = _install_root()
    missing: list[str] = []
    for package in LTX25_VENDORED_PACKAGES:
        package_dir, problem = _resolve_vendored_package(package, install_root)
        if problem is not None:
            reason, detail = problem
            return LTX25Runtime(
                state="corrupt", source="vendored", detail=detail, reason=reason
            )
        if package_dir is None:
            missing.append(package)
            continue
        provenance = _read_vendored_provenance(package_dir)
        if provenance is None:
            return LTX25Runtime(
                state="corrupt",
                source="vendored",
                detail=(
                    f"{package} has no usable {LTX25_PROVENANCE_FILE} provenance "
                    "metadata."
                ),
                reason="damaged",
            )
        expected = {
            "REPOSITORY": LTX25_RUNTIME_REPOSITORY,
            "COMMIT": LTX25_RUNTIME_COMMIT,
            "VERSION": LTX25_RUNTIME_VERSION,
            "PACKAGE": package,
        }
        for name, value in expected.items():
            if provenance.get(name) != value:
                return LTX25Runtime(
                    state="corrupt",
                    source="vendored",
                    detail=(
                        f"{package} provenance {name} is "
                        f"{provenance.get(name)!r}, expected {value!r}."
                    ),
                    reason="damaged",
                )
        if package == "ltx_pipelines_mlx" and not (package_dir / "cli.py").is_file():
            return LTX25Runtime(
                state="corrupt",
                source="vendored",
                detail="ltx_pipelines_mlx.cli is missing from the vendored package.",
                reason="damaged",
            )
        try:
            digest = _tree_digest(package_dir)
        except OSError:
            return LTX25Runtime(
                state="corrupt",
                source="vendored",
                detail=f"{package} files could not be read for verification.",
                reason="damaged",
            )
        if digest != provenance["TREE_SHA256"]:
            return LTX25Runtime(
                state="corrupt",
                source="vendored",
                detail=(
                    f"{package} files no longer match the audited snapshot "
                    f"({digest} != {provenance['TREE_SHA256']})."
                ),
                reason="damaged",
            )
    if missing:
        return LTX25Runtime(
            state="absent"
            if len(missing) == len(LTX25_VENDORED_PACKAGES)
            else "corrupt",
            source="vendored",
            detail="missing vendored package(s): " + ", ".join(missing),
            reason="missing"
            if len(missing) == len(LTX25_VENDORED_PACKAGES)
            else "damaged",
        )
    return LTX25Runtime(state="trusted", source="vendored", executable=sys.executable)


def ltx25_runtime() -> LTX25Runtime:
    """Resolve the runtime once into a closed state.

    Precedence is explicit and never falls through: the Python floor, then the
    ``RAPID_MLX_LTX25_RUNTIME`` override, then the bundled copy. A broken
    override is reported as ``override_invalid`` rather than quietly running
    the bundled runtime.
    """
    if sys.version_info < (3, 11):
        return LTX25Runtime(state="python_unsupported")
    executable = resolve_ltx25_runtime()
    if executable is not None:
        return LTX25Runtime(state="trusted", source="override", executable=executable)
    if os.environ.get("RAPID_MLX_LTX25_RUNTIME", "").strip():
        return LTX25Runtime(
            state="override_invalid",
            source="override",
            detail=(
                "The LTX-2.5 runtime override (RAPID_MLX_LTX25_RUNTIME) does "
                "not point at an executable ltx-2-mlx checkout at the pinned "
                f"revision ({LTX25_RUNTIME_COMMIT})."
            ),
        )
    return _vendored_runtime()


def python_unsupported_detail() -> str:
    """Explain the LTX-2.5 Python floor in standalone terms."""
    return (
        "LTX-2.5 video generation requires Python 3.11 or newer "
        f"(current: {sys.version_info.major}.{sys.version_info.minor}). "
        "Rapid-MLX core still supports Python 3.10, but the LTX-2.5 runtime "
        "does not."
    )


def runtime_unavailable_message(runtime: LTX25Runtime) -> str:
    """Return the actionable generation-time message for a non-trusted state."""
    if runtime.state == "python_unsupported":
        return python_unsupported_detail()
    if runtime.state == "override_invalid":
        return (
            (runtime.detail or "The LTX-2.5 runtime override is invalid.")
            + " Fix or unset RAPID_MLX_LTX25_RUNTIME; see the LTX-2.5 setup in "
            "the video generation guide."
        )
    if runtime.reason == "shadowed":
        return (
            (
                runtime.detail
                or "A different LTX-2.5 runtime is shadowing the bundled copy."
            )
            + " Remove the shadowing path from PYTHONPATH or run rapid-mlx from "
            "a different working directory; see the LTX-2.5 setup in the video "
            "generation guide."
        )
    return (
        "The LTX-2.5 runtime shipped with rapid-mlx is missing or damaged in "
        "this installation. Reinstall rapid-mlx to restore it."
    )


def embedded_ltx25_interpreter() -> str | None:
    """Return this interpreter when the audited runtime is bundled here."""
    runtime = _vendored_runtime()
    return sys.executable if runtime.state == "trusted" else None


def _runtime_revision(executable: str) -> str | None:
    """Verify the documented workspace points at the pinned Git revision."""
    path = Path(executable)
    try:
        repository = path.parents[2]
    except IndexError:
        return None
    if not (repository / ".git").exists():
        return None
    if path.absolute() != (repository / ".venv" / "bin" / "ltx-2-mlx").absolute():
        return None
    try:

        def git(*arguments: str) -> subprocess.CompletedProcess[str]:
            return subprocess.run(
                ["git", "-C", str(repository), *arguments],
                check=True,
                capture_output=True,
                text=True,
                timeout=5,
                env={**os.environ, "GIT_NO_REPLACE_OBJECTS": "1"},
            )

        result = git("rev-parse", "HEAD")
        git("ls-files", "--error-unmatch", "uv.lock")
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
        return None
    return result.stdout.strip()


def _materialize_runtime(repository: Path, destination: Path) -> None:
    """Extract only tracked files from the audited commit into a fresh tree."""
    try:
        archive = subprocess.run(
            [
                "git",
                "-C",
                str(repository),
                "archive",
                "--format=tar",
                LTX25_RUNTIME_COMMIT,
            ],
            check=True,
            capture_output=True,
            timeout=30,
            env={**os.environ, "GIT_NO_REPLACE_OBJECTS": "1"},
        ).stdout
        root = destination.resolve()
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:") as source:
            members = source.getmembers()
            for member in members:
                target = (destination / member.name).resolve()
                if not target.is_relative_to(root) or not (
                    member.isfile() or member.isdir()
                ):
                    raise LTX25BackendError(
                        "The pinned LTX-2.5 source archive contains an unsafe entry."
                    )
            # Members are pre-validated above; the stdlib ``data`` filter is
            # defense in depth where available (3.10.12+/3.11.4+) and silences
            # the Python 3.14 default-filter DeprecationWarning.
            if hasattr(tarfile, "data_filter"):
                source.extractall(destination, members=members, filter="data")
            else:
                source.extractall(destination, members=members)
    except (
        OSError,
        subprocess.CalledProcessError,
        subprocess.TimeoutExpired,
        tarfile.TarError,
    ) as exc:
        raise LTX25BackendError(
            "The pinned LTX-2.5 source snapshot could not be materialized."
        ) from exc


# URLs with userinfo (https://user:token@index.example, including
# percent-encoded forms like https://build%40corp:s3cret@…) can appear in
# uv's package-index error output; redact the ENTIRE userinfo before
# display — anything between ``scheme://`` and ``@`` is treated as
# potentially credential-bearing.
_CREDENTIAL_URL_RE = re.compile(r"(\w[\w+.-]*://)[^/@\s]+@")
# Token-bearing query parameters / assignments (``?token=…``,
# ``access_key=…``, ``Authorization: Bearer …``) that package-index
# errors can echo back.
# Any identifier ENDING in a credential noun (token / secret / password /
# passwd / key / credential, optional plural) — covers access_token,
# client_secret, api-key, HF_TOKEN, AWS_SECRET_ACCESS_KEY, … without
# enumerating prefixes. Values may be bare or quoted.
_CREDENTIAL_PARAM_RE = re.compile(
    # Suffix set includes signed-URL auth params (codex on #2166):
    # ``X-Amz-Signature=``, ``sig=`` (Azure SAS), ``sas=``, ``auth=``,
    # ``jwt=`` — none of which end in the classic credential suffixes,
    # and uv stderr can echo a full index URL query string verbatim.
    r"(?i)((?<![\w-])[\w-]*"
    r"(?:token|secret|password|passwd|key|credential|signature|sig|auth|sas|jwt)s?"
    r"\s*[=:]\s*)(?:\"[^\"]*\"|'[^']*'|[^&\s\"']+)"
)
_BEARER_RE = re.compile(r"(?i)\b(bearer\s+)[a-z0-9._~+/=-]+")
# Any ``Authorization:``-style header value regardless of scheme (Basic,
# Digest, custom) — the scheme word is kept, the credential is redacted.
_AUTH_HEADER_RE = re.compile(r"(?i)\b(authorization\s*[=:]\s*[a-z0-9_-]+\s+)[^\s\"']+")


def _sanitize_diagnostic(text: str) -> str:
    """Make subprocess output safe to print: no control sequences (terminal
    escape injection), no embedded index credentials (URL userinfo,
    token-bearing query params, bearer headers)."""
    text = _CREDENTIAL_URL_RE.sub(r"\1***@", text)
    text = _AUTH_HEADER_RE.sub(r"\1***", text)
    text = _CREDENTIAL_PARAM_RE.sub(r"\1***", text)
    text = _BEARER_RE.sub(r"\1***", text)
    return "".join(ch if ch.isprintable() or ch in " \t\n" else " " for ch in text)


def _stderr_tail(stream: io.BufferedRandom) -> str:
    """Read a bounded tail from a spooled stderr file (never the whole body)."""
    try:
        stream.seek(0, os.SEEK_END)
        size = stream.tell()
        stream.seek(max(0, size - 4096))
        return stream.read().decode("utf-8", errors="replace")
    except (OSError, ValueError):
        return ""


def _bounded(text: str) -> str:
    return text[:300] + "…" if len(text) > 300 else text


def _provisioning_failure_detail(exc: Exception) -> str:
    """Compress a provisioning failure into one actionable, sanitized line.

    EVERY exception-derived string passes through ``_sanitize_diagnostic``
    and the length bound — ``OSError`` messages can embed paths or
    environment-derived text with the same control-sequence/credential
    exposure as uv's stderr.
    """
    if isinstance(exc, subprocess.TimeoutExpired):
        return f"`uv sync --frozen` timed out after {int(exc.timeout)}s"
    if isinstance(exc, subprocess.CalledProcessError):
        detail = f"`uv sync --frozen` failed with exit code {exc.returncode}"
        stderr = _sanitize_diagnostic((exc.stderr or "").strip())
        if stderr:
            detail += f" ({_bounded(' | '.join(stderr.splitlines()[-3:]))})"
        return detail
    return _bounded(_sanitize_diagnostic(str(exc))) or type(exc).__name__


def prepare_ltx25_runtime(executable: str) -> Path:
    """Provision the pinned runtime once per selected executable."""
    key = os.path.abspath(executable)

    with _RUNTIME_CACHE_LOCK:
        prepared = _RUNTIME_CACHE.get(key)
        if prepared is not None:
            return Path(prepared.name)
        uv = shutil.which("uv")
        if uv is None:
            raise LTX25BackendError(
                "LTX-2.5 support requires uv to build its pinned runtime."
            )
        cache: tempfile.TemporaryDirectory[str] | None = None
        try:
            cache = tempfile.TemporaryDirectory(prefix="rapidmlx-ltx25-runtime-")
            workspace = Path(cache.name)
            _materialize_runtime(Path(executable).parents[2], workspace)
            # stderr goes to a temp file, not PIPE: a noisy dependency build
            # must never buffer unbounded output in the server's memory. Only
            # a bounded tail is read back, and only on failure.
            with tempfile.TemporaryFile() as uv_stderr:
                try:
                    subprocess.run(
                        [
                            str(Path(uv).absolute()),
                            "sync",
                            "--frozen",
                            "--project",
                            str(workspace),
                        ],
                        check=True,
                        stdout=subprocess.DEVNULL,
                        stderr=uv_stderr,
                        timeout=1800,
                        env=_isolated_python_environment(),
                    )
                except subprocess.CalledProcessError as run_exc:
                    # Real runs route stderr to the file, so the exception
                    # carries none; keep any stderr already attached.
                    if not run_exc.stderr:
                        run_exc.stderr = _stderr_tail(uv_stderr)
                    raise
            interpreter = workspace / ".venv" / "bin" / "python"
            if not interpreter.is_file() or not os.access(interpreter, os.X_OK):
                raise LTX25BackendError(
                    "The pinned LTX-2.5 runtime did not create its Python environment."
                )
        except LTX25BackendError:
            if cache is not None:
                cache.cleanup()
            raise
        except (
            OSError,
            subprocess.CalledProcessError,
            subprocess.TimeoutExpired,
        ) as exc:
            if cache is not None:
                cache.cleanup()
            raise LTX25BackendError(
                "The pinned LTX-2.5 runtime could not be provisioned: "
                + _provisioning_failure_detail(exc)
            ) from exc
        _RUNTIME_CACHE[key] = cache
        return workspace


def _prepared_ltx25_runtime(executable: str) -> Path | None:
    with _RUNTIME_CACHE_LOCK:
        prepared = _RUNTIME_CACHE.get(os.path.abspath(executable))
        return Path(prepared.name) if prepared is not None else None


def _generation_timeout_seconds() -> int:
    raw = os.environ.get("RAPID_MLX_LTX25_TIMEOUT_SEC", "").strip()
    if not raw:
        return _DEFAULT_TIMEOUT_SECONDS
    try:
        value = int(raw)
    except ValueError as exc:
        raise LTX25BackendError(
            "The LTX-2.5 timeout must be an integer number of seconds."
        ) from exc
    if value < 60:
        raise LTX25BackendError("The LTX-2.5 timeout must be at least 60 seconds.")
    return value


class LTX25BackendError(RuntimeError):
    """Safe, public-facing error from the LTX-2.5 backend."""


class LTX25VideoEngine:
    """Run LTX-2.5 through its native MLX command-line runtime."""

    native_fps = 24

    def __init__(self, model_name: str) -> None:
        self.model_name = model_name
        self._process_lock = threading.Lock()
        self._process: subprocess.Popen[str] | None = None
        self._stopping = False

    @staticmethod
    def _terminate_process(process: subprocess.Popen[str]) -> None:
        leader_running = process.poll() is None
        if not leader_running:
            # The runner is a group supervisor: before it exits it signals the
            # still-owned process group, so no stale PGID needs to be reused.
            return
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            process.wait(timeout=_TERMINATE_GRACE_SECONDS)
            return
        try:
            process.wait(timeout=_TERMINATE_GRACE_SECONDS)
            return
        except subprocess.TimeoutExpired:
            # The unreaped leader still owns this PID/PGID, so reuse is
            # impossible and escalation is safe.
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        try:
            process.wait(timeout=_TERMINATE_GRACE_SECONDS)
        except subprocess.TimeoutExpired as exc:
            raise LTX25BackendError(
                "The LTX-2.5 runtime process group could not be reaped."
            ) from exc

    def stop(self) -> None:
        """Stop an active external generation during bounded shutdown."""
        with self._process_lock:
            self._stopping = True
            process = self._process
        if process is not None:
            self._terminate_process(process)

    def generate(
        self,
        *,
        prompt: str,
        output_path: Path,
        width: int,
        height: int,
        num_frames: int,
        fps: int,
        seed: int,
        image: Path | None,
        conditioning_strength: float | None = None,
        on_loaded: Callable[[], None] | None = None,
    ) -> None:
        command = [
            "generate",
            "--model",
            self.model_name,
            "--distilled",
            "--low-ram",
            "--quiet",
            "--height",
            str(height),
            "--width",
            str(width),
            "--frames",
            str(num_frames),
            "--frame-rate",
            str(fps),
            "--seed",
            str(seed),
        ]
        if image is not None:
            command.extend(
                [
                    "--image",
                    str(image),
                    "0",
                    str(
                        1.0 if conditioning_strength is None else conditioning_strength
                    ),
                ]
            )
        self._run_runtime(
            command=command,
            prompt=prompt,
            output_path=output_path,
            on_loaded=on_loaded,
        )

    def extend(
        self,
        *,
        prompt: str,
        source_video: Path,
        output_path: Path,
        extend_frames: int,
        seed: int,
        on_loaded: Callable[[], None] | None = None,
    ) -> None:
        """Append a multiple of eight pixel frames using video context."""
        if extend_frames < 8 or extend_frames % 8:
            raise LTX25BackendError("LTX-2.5 extension requires 8n added frames.")
        self._run_runtime(
            command=[
                "extend",
                "--model",
                self.model_name,
                "--quiet",
                "--video",
                str(source_video),
                "--extend-frames",
                str(extend_frames // 8),
                "--direction",
                "after",
                "--seed",
                str(seed),
            ],
            prompt=prompt,
            output_path=output_path,
            on_loaded=on_loaded,
        )

    def _run_runtime(
        self,
        *,
        command: list[str],
        prompt: str,
        output_path: Path,
        on_loaded: Callable[[], None] | None,
    ) -> None:
        timeout = _generation_timeout_seconds()
        environment = os.environ.copy()
        # Selection is re-evaluated here rather than trusting a previously
        # prepared workspace: the override may have changed or been unset.
        runtime = ltx25_runtime()
        pinned_root = ""
        interpreter: str | None = None
        if runtime.state == "trusted" and runtime.source == "vendored":
            interpreter = runtime.executable
            pinned_root = str(_install_root())
        elif runtime.state == "trusted" and runtime.executable is not None:
            workspace = _prepared_ltx25_runtime(runtime.executable)
            if workspace is None:
                workspace = prepare_ltx25_runtime(runtime.executable)
            interpreter = str(workspace / ".venv" / "bin" / "python")
            environment = _isolated_python_environment()
        else:
            raise LTX25BackendError(runtime_unavailable_message(runtime))
        assert interpreter is not None
        try:
            staging = tempfile.TemporaryDirectory(
                prefix=f".{output_path.name}.",
                dir=output_path.parent,
            )
            staged_output = Path(staging.name) / "output.mp4"
        except OSError as exc:
            raise LTX25BackendError(
                "LTX-2.5 generation could not create its temporary output."
            ) from exc

        output_option = ["--output", str(staged_output)]
        if "--image" in command:
            # Keep the image's three positional arguments together at the end.
            image_index = command.index("--image")
            command = [*command[:image_index], *output_option, *command[image_index:]]
        else:
            command = [*command, *output_option]
        command = [
            interpreter,
            "-P",
            "-c",
            _STDIN_PROMPT_RUNNER,
            pinned_root,
            *command,
        ]
        process: subprocess.Popen[str] | None = None
        ready_read: int | None = None
        ready_write: int | None = None
        readiness_thread: threading.Thread | None = None
        try:
            # Prompts may contain private user data. Keep them out of argv and
            # local process listings by feeding the isolated runtime over stdin.
            with self._process_lock:
                if self._stopping:
                    raise LTX25BackendError(
                        "LTX-2.5 generation cannot start while the server is stopping."
                    )
                ready_read, ready_write = os.pipe()
                environment[_READINESS_FD_ENV] = str(ready_write)
                try:
                    process = subprocess.Popen(
                        command,
                        stdin=subprocess.PIPE,
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                        text=True,
                        start_new_session=True,
                        env=environment,
                        pass_fds=(ready_write,),
                    )
                finally:
                    os.close(ready_write)
                    ready_write = None
                self._process = process

            assert ready_read is not None
            readiness_fd = ready_read

            def await_readiness(fd: int = readiness_fd) -> None:
                with os.fdopen(fd, "rb") as stream:
                    token = stream.readline(len(_READINESS_TOKEN) + 1)
                if token == _READINESS_TOKEN and on_loaded is not None:
                    on_loaded()

            readiness_thread = threading.Thread(target=await_readiness, daemon=True)
            readiness_thread.start()
            ready_read = None
            process.communicate(input=prompt, timeout=timeout)
            readiness_thread.join()
            if process.returncode == _CHILD_PROVENANCE_EXIT:
                raise LTX25BackendError(
                    "The bundled LTX-2.5 runtime no longer matches the audited "
                    "snapshot; refusing to run it. Reinstall rapid-mlx to restore "
                    "the bundled runtime."
                )
            if process.returncode:
                raise LTX25BackendError(
                    f"LTX-2.5 runtime exited with code {process.returncode}; "
                    "runtime output is not retained because it may contain request data."
                )
            if not staged_output.is_file() or staged_output.stat().st_size == 0:
                raise LTX25BackendError(
                    "LTX-2.5 generation completed without an MP4 output."
                )
            os.replace(staged_output, output_path)
        except subprocess.TimeoutExpired as exc:
            if process is not None:
                self._terminate_process(process)
            raise LTX25BackendError(
                "LTX-2.5 generation exceeded its configured time limit."
            ) from exc
        except LTX25BackendError:
            if process is not None:
                self._terminate_process(process)
            raise
        except BaseException as exc:
            if process is not None:
                self._terminate_process(process)
            if isinstance(exc, (KeyboardInterrupt, SystemExit)):
                raise
            raise LTX25BackendError(
                "LTX-2.5 generation failed while running its isolated runtime."
            ) from exc
        finally:
            if ready_read is not None:
                os.close(ready_read)
            if readiness_thread is not None:
                readiness_thread.join(timeout=1)
            with self._process_lock:
                if self._process is process:
                    self._process = None
            staging.cleanup()
