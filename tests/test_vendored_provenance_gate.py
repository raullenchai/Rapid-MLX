import io
import json
import subprocess
import sys
import zipfile
from pathlib import Path

import pytest

from scripts.check_vendored_provenance import VENDOR, digest, verify


@pytest.fixture
def source_tree(tmp_path):
    root = tmp_path / VENDOR
    newer = root / "models/minicpmv4_7"
    newer.mkdir(parents=True)
    commit = "a" * 40
    source = f"# upstream {commit}\nVALUE = 1\n".encode()
    (newer / "model.py").write_bytes(source)
    inventory = {
        "upstream_commit": commit,
        "files": {"model.py": {"vendored_sha256": digest(source)}},
    }
    (newer / "provenance.json").write_text(json.dumps(inventory))
    (root / "cache.py").write_text("# reviewed local adaptation\n")
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr("mlx_vlm/models/cache.py", b"# pinned upstream\n")
    wheel = buffer.getvalue()
    files = {
        path.relative_to(root).as_posix(): {
            "vendored_sha256": digest(path.read_bytes()),
            "upstream_commit": commit,
        }
        for path in root.rglob("*")
        if path.is_file()
    }
    files["cache.py"] = {
        "vendored_sha256": digest((root / "cache.py").read_bytes()),
        "wheel_path": "mlx_vlm/models/cache.py",
        "upstream_sha256": digest(b"# pinned upstream\n"),
    }
    manifest = {"wheel": {"sha256": digest(wheel)}, "files": files}
    return tmp_path, manifest, wheel


def test_verified_tree_ignores_only_python_cache(source_tree):
    root, manifest, wheel = source_tree
    cache = root / VENDOR / "__pycache__"
    cache.mkdir()
    (cache / "cache.cpython-313.pyc").write_bytes(b"irrelevant generated bytecode")
    verify(root, manifest, wheel)


@pytest.mark.parametrize("mutation", ["changed", "added", "deleted", "symlink"])
def test_vendor_drift_fails_closed(source_tree, mutation):
    root, manifest, wheel = source_tree
    path = root / VENDOR / "cache.py"
    if mutation == "changed":
        path.write_text("# unreviewed edit\n")
    elif mutation == "added":
        (path.parent / "extra.py").write_text("# hidden new module\n")
    elif mutation == "deleted":
        path.unlink()
    else:
        target = root / "outside.py"
        target.write_bytes(path.read_bytes())
        path.unlink()
        path.symlink_to(target)
    with pytest.raises(ValueError, match="Vendor inventory drift|Unreviewed vendor"):
        verify(root, manifest, wheel)


def test_wheel_is_authenticated_before_zip_parser(source_tree):
    root, manifest, _ = source_tree
    with pytest.raises(ValueError, match="wheel SHA-256 mismatch"):
        verify(root, manifest, b"not a zip, not executed")


def test_wrong_upstream_member_hash_is_rejected(source_tree):
    root, manifest, wheel = source_tree
    manifest["files"]["cache.py"]["upstream_sha256"] = "0" * 64
    with pytest.raises(ValueError, match="Upstream provenance mismatch"):
        verify(root, manifest, wheel)


def test_checker_imports_with_no_site_packages():
    script = (
        Path(__file__).resolve().parents[1] / "scripts/check_vendored_provenance.py"
    )
    subprocess.run(
        [sys.executable, "-S", str(script), "--help"], check=True, capture_output=True
    )


