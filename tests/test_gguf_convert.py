def test_bits4_report_compares_bf16_vs_quant(converted_4bit):
    """--report defaults to on with --bits: ppl for both products is recorded.

    The fixture's weights are random, so the absolute ppl values are noise;
    what matters is that both passes ran and the delta was computed.
    """
    _out, result = converted_4bit
    rep = result.report
    assert rep is not None, "report should run by default when --bits is given"
    assert rep["ppl_reference"] > 0
    assert rep["ppl_candidate"] > 0
    assert rep["tokens"] > 0
    assert rep["candidate_label"] == "4-bit"
    expected_delta = (
        (rep["ppl_candidate"] - rep["ppl_reference"]) / rep["ppl_reference"] * 100
    )
    assert rep["delta_pct"] == pytest.approx(expected_delta)


