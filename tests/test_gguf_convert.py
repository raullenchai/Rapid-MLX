def test_f16_values_exact_after_roundtrip(converted):
    from vllm_mlx.gguf_convert import _reverse_permute_qk

    tensors = _make_tensors()
    weights = {
        k: np.array(v.astype(mx.float32))
        for k, v in mx.load(str(converted / "model.safetensors")).items()
    }
    np.testing.assert_array_equal(
        weights["model.embed_tokens.weight"],
        tensors["token_embd.weight"][0].astype(np.float32),
    )
    # llama q/k are stored in GGUF's interleaved-rope layout; the converter
    # must apply the reverse permutation (transformers' LlamaTensorProcessor
    # semantics), so the expected value is the *unpermuted* fixture bytes.
    np.testing.assert_array_equal(
        weights["model.layers.1.self_attn.k_proj.weight"],
        _reverse_permute_qk(
            tensors["blk.1.attn_k.weight"][0].astype(np.float32), _HEADS, _KV_HEADS
        ),
    )
    np.testing.assert_array_equal(
        weights["model.norm.weight"],
        tensors["output_norm.weight"][0].astype(np.float32),
    )


def test_q4_0_values_within_quant_tolerance(converted):
    from vllm_mlx.gguf_convert import _reverse_permute_qk

    tensors = _make_tensors()
    weights = {
        k: np.array(v.astype(mx.float32))
        for k, v in mx.load(str(converted / "model.safetensors")).items()
    }
    # Expected values: dequantize the exact Q4_0 bytes the fixture carries
    # (q_proj additionally goes through the llama reverse permutation).
    expected_q = _reverse_permute_qk(
        dequantize(tensors["blk.0.attn_q.weight"][0], GGMLQuantizationType.Q4_0),
        _HEADS,
        _HEADS,
    )
    got_q = weights["model.layers.0.self_attn.q_proj.weight"]
    assert got_q.shape == expected_q.shape == (_DIM, _DIM)
    np.testing.assert_allclose(got_q, expected_q, rtol=0.02, atol=0.02)

    expected_g = dequantize(
        tensors["blk.1.ffn_gate.weight"][0], GGMLQuantizationType.Q4_0
    )
    got_g = weights["model.layers.1.mlp.gate_proj.weight"]
    assert got_g.shape == expected_g.shape == (_FFN, _DIM)
    np.testing.assert_allclose(got_g, expected_g, rtol=0.02, atol=0.02)


