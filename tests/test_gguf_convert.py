# ----- tiny GGUF fixture ----------------------------------------------------

_DIM = 64
_LAYERS = 2
_FFN = 128
_HEADS = 4
_KV_HEADS = 2
_CTX = 128
_VOCAB = 256

# Deterministic value source; small integers are exact in f16/bf16/f32, so
# f16 tensors can be asserted with zero tolerance after the round trip.
_RNG = np.random.default_rng(20260721)


def _exact_f16(shape: tuple[int, ...]) -> np.ndarray:
    return _RNG.integers(-3, 4, size=shape).astype(np.float32).astype(np.float16)


def _q4_0(shape: tuple[int, ...]) -> np.ndarray:
    """Quantize a random f32 tensor to Q4_0 bytes (last dim must be %32)."""
    assert shape[-1] % 32 == 0
    return quantize(
        _RNG.standard_normal(shape).astype(np.float32), GGMLQuantizationType.Q4_0
    )


# Tensors of the fixture: (ggml_name, kind, numpy_logical_shape). Values are
# regenerated by the same seeded RNG in _expected_weights() below — order of
# generation must match exactly between the two.
_LAYOUT: list[tuple[str, str, tuple[int, ...]]] = [
    ("token_embd.weight", "f16", (_VOCAB, _DIM)),
]
for _i in range(_LAYERS):
    _LAYOUT += [
        (f"blk.{_i}.attn_norm.weight", "f16", (_DIM,)),
        (f"blk.{_i}.attn_q.weight", "q4_0", (_DIM, _DIM)),
        (f"blk.{_i}.attn_k.weight", "f16", (_DIM // _HEADS * _KV_HEADS, _DIM)),
        (f"blk.{_i}.attn_v.weight", "f16", (_DIM // _HEADS * _KV_HEADS, _DIM)),
        (f"blk.{_i}.attn_output.weight", "f16", (_DIM, _DIM)),
        (f"blk.{_i}.ffn_norm.weight", "f16", (_DIM,)),
        (f"blk.{_i}.ffn_gate.weight", "q4_0", (_FFN, _DIM)),
        (f"blk.{_i}.ffn_up.weight", "f16", (_FFN, _DIM)),
        (f"blk.{_i}.ffn_down.weight", "f16", (_DIM, _FFN)),
    ]
_LAYOUT += [
    ("output_norm.weight", "f16", (_DIM,)),
    # Deliberately no ``output.weight``: exercises the tie_word_embeddings
    # detection (llama.cpp omits the output tensor for tied models).
]


def _make_tensors() -> dict[str, tuple[np.ndarray, str]]:
    """Regenerate the fixture's tensor values (seeded → deterministic)."""
    rng = np.random.default_rng(20260721)
    out: dict[str, tuple[np.ndarray, str]] = {}
    for name, kind, shape in _LAYOUT:
        if kind == "f16":
            out[name] = (
                rng.integers(-3, 4, size=shape).astype(np.float32).astype(np.float16),
                kind,
            )
        else:
            out[name] = (
                quantize(
                    rng.standard_normal(shape).astype(np.float32),
                    GGMLQuantizationType.Q4_0,
                ),
                kind,
            )
    return out


def _write_tiny_gguf(
    path: Path, base_repo: str | None = None
) -> dict[str, tuple[np.ndarray, str]]:
    """Write the tiny llama GGUF; returns ``{ggml_name: (data, kind)}``."""
    tensors = _make_tensors()
    w = GGUFWriter(str(path), arch="llama")
    w.add_name("tiny-llama-fixture")
    w.add_context_length(_CTX)
    w.add_embedding_length(_DIM)
    w.add_block_count(_LAYERS)
    w.add_feed_forward_length(_FFN)
    w.add_head_count(_HEADS)
    w.add_head_count_kv(_KV_HEADS)
    w.add_layer_norm_rms_eps(1e-5)
    w.add_rope_freq_base(10000.0)
    w.add_vocab_size(_VOCAB)
    # Minimal byte-level-BPE-shaped vocab plus two merge products (BPE
    # requires the *result* of every merge rule to be in the vocab), so
    # transformers' converter takes the BPE (not the scores) branch.
    # bos/eos/unk map onto the first three tokens.
    tokens = (
        ["<s>", "</s>", "<unk>"]
        + [f"t{i}" for i in range(_VOCAB - 5)]
        + ["t3t4", "t5t6"]
    )
    w.add_tokenizer_model("gpt2")
    w.add_tokenizer_pre("default")
    w.add_token_list(tokens)
    w.add_token_merges(["t3 t4", "t5 t6"])
    w.add_bos_token_id(0)
    w.add_eos_token_id(1)
    w.add_unk_token_id(2)
    if base_repo is not None:
        w.add_base_model_count(1)
        w.add_base_model_repo_url(0, f"https://huggingface.co/{base_repo}")
    w.add_file_type(int(GGMLQuantizationType.F16))
    for name, kind, _shape in _LAYOUT:
        data, _ = tensors[name]
        if kind == "q4_0":
            w.add_tensor(name, data, raw_dtype=GGMLQuantizationType.Q4_0)
        else:
            w.add_tensor(name, data)
    w.open_output_file()
    w.write_header_to_file()
    w.write_kv_data_to_file()
    w.write_tensors_to_file()
    w.close()
    return tensors


